"""
Cross-lingual check: do Marathi/Hindi questions find on-topic English KB
questions, with and without glossary expansion (src/triage/expansion.py)?

Held-out set: config/crosslingual_heldout.csv, written after the glossary was
frozen. A hit counts when the top-1 retrieved KB question contains one of the
topic keywords fixed in the CSV before the first run.

    python -m src.triage.crosslingual
"""
from __future__ import annotations

import pandas as pd

from src.triage.classifier import QueryClassifier
from src.triage.config import CONFIG_DIR, gate_thresholds, path
from src.triage.embeddings import embed_texts
from src.triage.expansion import expand_query
from src.triage.retrieval import Retriever

VARIANTS = {"plain": lambda t: t, "expanded": expand_query}


def retrieval_check(retriever: Retriever) -> tuple[dict, list[dict]]:
    held = pd.read_csv(CONFIG_DIR / "crosslingual_heldout.csv", dtype=str, keep_default_na=False)
    scores, rows = {}, []
    for name, fn in VARIANTS.items():
        vecs = embed_texts([fn(t) for t in held["text"]])
        hits = retriever.search_batch(vecs, k=1)
        ok = 0
        for (text, kw), h in zip(zip(held["text"], held["topic_keywords"]), hits):
            top = h[0].question if h else ""
            good = any(k in top.lower() for k in kw.split("|"))
            ok += good
            rows.append({"variant": name, "text": text, "top1": top, "on_topic": good, "similarity": h[0].similarity if h else None})
        scores[name] = {"correct": ok, "n": len(held)}
    return scores, rows


def classifier_check(clf: QueryClassifier) -> dict:
    probes = pd.read_csv(CONFIG_DIR / "gate_probes.csv", dtype=str, keep_default_na=False)
    probes = probes[(probes["lang"] != "en") & (probes["expected_query_type"] != "")]
    out = {}
    for name, fn in VARIANTS.items():
        texts = [fn(t) for t in probes["text"]]
        pred = clf.query_type.predict(texts, embed_texts(texts))
        out[name] = {"correct": int((pred == probes["expected_query_type"].values).sum()), "n": len(probes)}
    return out


def report(ret: dict, rows: list[dict], cls: dict, answer_threshold: float) -> str:
    expanded_sims = [r["similarity"] for r in rows if r["variant"] == "expanded" and r["similarity"] is not None]
    reach = sum(s >= answer_threshold for s in expanded_sims)
    lines = [
        "# Stage 2 - Cross-lingual retrieval",
        "",
        "Generated by `python -m src.triage.crosslingual`.",
        "",
        "Farmers ask in Marathi or Hindi; every KB question is an English call-taker summary.",
        "The small model probe (`embedding_model_probe.md`, 15 candidate questions) made plain",
        "multilingual embeddings look adequate. Against the **real** knowledge base (~78k",
        "distinct questions) they are not: dense, generic scheme questions crowd out the",
        "right topic. Glossary expansion (`config/query_glossary.yaml`) appends English names",
        "of recognised crops and farm terms to Devanagari questions before embedding.",
        "",
        "## Held-out retrieval (top-1 KB question on topic)",
        "",
        "12 questions written after the glossary was frozen; topic keywords fixed before the",
        "first run (`config/crosslingual_heldout.csv`). Production KB.",
        "",
        "| Variant | On topic |",
        "|---|---:|",
    ]
    for name, s in ret.items():
        lines.append(f"| {name} | **{s['correct']}/{s['n']}** |")
    lines += ["", "| Variant | Question | Top-1 KB question | Sim | On topic |", "|---|---|---|---:|:-:|"]
    for r in rows:
        sim = "-" if r["similarity"] is None else f"{r['similarity']:.3f}"
        lines.append(f"| {r['variant']} | {r['text']} | {r['top1']} | {sim} | {'yes' if r['on_topic'] else 'no'} |")
    lines += [
        "",
        "Reading the misses by hand: keyword matching is strict (a misspelled \"VARITIES\" counts",
        "as a miss), and an on-topic hit can still name the wrong crop. Treat 12 questions as a",
        "smoke test; the recorded voice set should repeat this at scale.",
        "",
        "## Query-type classifier on Marathi/Hindi probes",
        "",
        "| Variant | Correct |",
        "|---|---:|",
    ]
    for name, s in cls.items():
        lines.append(f"| {name} | {s['correct']}/{s['n']} |")
    lines += [
        "",
        "## Effect on the gate",
        "",
        "Expansion is applied only to Devanagari input, so English questions are embedded exactly",
        f"as during calibration. {reach} of {len(expanded_sims)} expanded held-out questions reach the "
        f"answer threshold ({answer_threshold:.3f}; best {max(expanded_sims, default=0):.3f}), so Marathi/Hindi",
        "questions fail safe to an expert: expansion buys better drafts and sources for the expert,",
        "not more automatic answers. Translating to English first (Stage 3) is the next step.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ret, rows = retrieval_check(Retriever.from_views())
    cls = classifier_check(QueryClassifier.load())
    out = path("reports") / "crosslingual_report.md"
    out.write_text(report(ret, rows, cls, gate_thresholds()["answer_min_similarity"]), encoding="utf-8")
    print(f"retrieval {ret} | classifier {cls}")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
